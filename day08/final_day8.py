import pandas as pd
data = {
    "Имя": ["Анна", "Иван", "Олег", "Мария", "Пётр", "Елена", "Сергей", "Наталья"],
    "Группа": ["1ИИ-1", "1ИИ-1", "1ИИ-2", "1ИИ-2", "1ИИ-1", "1ИИ-2", "1ИИ-1", "1ИИ-2"],
    "Баллы": [85, 72, 91, 64, 78, 88, 55, 95],
    "Посещено занятий": [18, 15, 20, 12, 17, 19, 10, 20]
}
df = pd.DataFrame(data)
df["Баллы после бонуса"] = df["Баллы"] + 5
print("1. Исходная таблица:")
print(df)
print("2. shape:", df.shape)
print("3. Столбцы:", df.columns.tolist())
print("4. Первые 3 строки:")
print(df.head(3))
print("5. Последние 2 строки:")
print(df.tail(2))
print("6. Средний балл:", df["Баллы"].mean())
print("7. Минимальный балл:", df["Баллы"].min())
print("8. Максимальный балл:", df["Баллы"].max())
print("9. Сумма посещённых занятий:", df["Посещено занятий"].sum())
print("10. Баллы 80 и выше:")
print(df[df["Баллы"] >= 80])
print("11. Группа 1ИИ-1:")
print(df[df["Группа"] == "1ИИ-1"])
print("12. Баллы от 60 до 80:")
print(df[(df["Баллы"] >= 60) & (df["Баллы"] <= 80)])
print("13. Только Имя и Баллы:")
print(df[["Имя", "Баллы"]])
print("14. Строка через loc:")
print(df.loc[0])
print("15. Строка через iloc:")
print(df.iloc[1])