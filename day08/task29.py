import pandas as pd
data = {
    "Товар": ["Ручка", "Тетрадь", "Книга", "Карандаш", "Линейка"],
    "Цена": [25, 40, 350, 15, 50],
    "Количество": [10, 5, 2, 20, 3]
}
df = pd.DataFrame(data)
print("Таблица:")
print(df)
df["Стоимость"] = df["Цена"] * df["Количество"]
print("С стоимостью:")
print(df)
print("Средняя цена:", df["Цена"].mean())
print("Самая дешёвая:", df["Цена"].min())
print("Самая дорогая:", df["Цена"].max())
print("Цена выше 30:")
print(df[df["Цена"] > 30])