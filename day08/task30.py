import pandas as pd
data = {
    "Имя": ["Анна", "Иван", "Олег", "Мария", "Пётр", "Елена"],
    "Группа": ["1ИИ-1", "1ИИ-1", "1ИИ-2", "1ИИ-2", "1ИИ-1", "1ИИ-2"],
    "Баллы": [85, 72, 91, 64, 78, 88]
}
df = pd.DataFrame(data)
print("Вся таблица:")
print(df)
print("Средний балл:", df["Баллы"].mean())
print("80 и выше:")
print(df[df["Баллы"] >= 80])
print("Группа 1ИИ-1:")
print(df[df["Группа"] == "1ИИ-1"])
print("Первые три:")
print(df.head(3))
print("Последние две:")
print(df.tail(2))