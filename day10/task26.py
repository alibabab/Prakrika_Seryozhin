import pandas as pd
import matplotlib.pyplot as plt
df = pd.read_csv("products.csv")
avg_price = df.groupby("Категория")["Цена"].mean().reset_index()
sum_qty = df.groupby("Категория")["Количество"].sum().reset_index()
print("Средняя цена:")
print(avg_price)
print("Сумма количества:")
print(sum_qty)
avg_price.to_csv("task26_avg_price.csv", index=False, encoding="utf-8")
plt.bar(avg_price["Категория"], avg_price["Цена"])
plt.title("Средняя цена по категориям")
plt.xlabel("Категория")
plt.ylabel("Цена")
plt.tight_layout()
plt.savefig("task26_chart.png")
plt.close()