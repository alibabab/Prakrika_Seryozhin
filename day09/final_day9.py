import pandas as pd
df = pd.read_csv("students_missing.csv")
print("1. Первые 5 строк:")
print(df.head())
print("2. shape:", df.shape)
print("3. columns:", df.columns.tolist())
print("4. dtypes:")
print(df.dtypes)
print("5. info:")
df.info()
print("6. Пропуски по столбцам:")
print(df.isna().sum())
avg_ball = df["Баллы"].mean()
df["Баллы"] = df["Баллы"].fillna(avg_ball)
df["Посещено"] = df["Посещено"].fillna(0)
print("7. После обработки пропусков:")
print(df)
df["Пропущено"] = 20 - df["Посещено"]
df["Процент посещаемости"] = (df["Посещено"] / 20 * 100).round(1)
print("8. С вычисляемыми столбцами:")
print(df)
print("9. Баллы 70 и выше:")
f1 = df[df["Баллы"] >= 70]
print(f1)
print("10. Посещено не меньше 16:")
f2 = df[df["Посещено"] >= 16]
print(f2)
print("11. Сортировка по баллам по убыванию:")
sorted_df = df.sort_values("Баллы", ascending=False)
print(sorted_df)
print("12. Среднее:", df["Баллы"].mean())
print("13. Минимум:", df["Баллы"].min())
print("14. Максимум:", df["Баллы"].max())
result = df[(df["Баллы"] >= 70) & (df["Посещено"] >= 15)]
result = result.reset_index(drop=True)
print("15. Итоговая таблица после фильтра:")
print(result)
result.to_csv("final_result_day9.csv", index=False, encoding="utf-8")
print("16. Сохранено в final_result_day9.csv")